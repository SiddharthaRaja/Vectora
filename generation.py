def main():
    parser = argparse.ArgumentParser(
        description="RAG Generation — GPT-4o-mini with citations"
    )
    parser.add_argument("--query",    type=str, help="Question to answer (omit for interactive mode)")
    parser.add_argument("--top-k",   type=int, default=TOP_K_CHUNKS, help="Chunks to retrieve")
    parser.add_argument("--year",     type=str, help="Filter by publication year")
    parser.add_argument("--paper-id", type=str, help="Filter by paper ID")
    args = parser.parse_args()

    # Check API key
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        print("\nERROR: OPENAI_API_KEY not set.")
        print("Either:")
        print("  1. Create a .env file with:  OPENAI_API_KEY=sk-...")
        print("  2. Or run:  $env:OPENAI_API_KEY = 'sk-...'  (PowerShell)")
        return

    # Clients
    openai_client = OpenAI(api_key=api_key)
    qdrant_client = QdrantClient(url=QDRANT_URL)

    # Filters
    filters = {}
    if args.year:
        filters["year"] = args.year
    if args.paper_id:
        filters["paper_id"] = args.paper_id

    if args.query:
        # Single query
        result = generate(
            args.query, qdrant_client, openai_client,
            top_k=args.top_k, filters=filters or None
        )
        result.pretty_print()

    else:
        # Interactive mode
        print("\nRAG Chatbot — powered by GPT-4o-mini + your research papers")
        print("Type 'quit' to exit\n")
        while True:
            try:
                query = input("You: ").strip()
            except (EOFError, KeyboardInterrupt):
                break
            if not query or query.lower() in ("quit", "exit", "q"):
                break
            result = generate(
                query, qdrant_client, openai_client,
                top_k=args.top_k, filters=filters or None
            )
            result.pretty_print()


if __name__ == "__main__":
    main()
