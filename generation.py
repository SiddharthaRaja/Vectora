# ─────────────────────────────────────────────
# Context builder
# ─────────────────────────────────────────────

def build_context(chunks: list[RetrievedChunk]) -> str:
    """Format retrieved chunks into a clear context block for the prompt."""
    blocks = []
    for i, chunk in enumerate(chunks, 1):
        author_short = chunk.authors.split(",")[0].strip() if chunk.authors else chunk.paper_id
        year = chunk.year or "n.d."
        blocks.append(
            f"SOURCE [{i}]\n"
            f"Title  : {chunk.title}\n"
            f"Authors: {chunk.authors}\n"
            f"Year   : {year}\n"
            f"Section: {chunk.section} | Page: {chunk.page}\n"
            f"DOI    : {chunk.doi}\n"
            f"---\n"
            f"{chunk.content}"
        )
    return "\n\n".join(blocks)


# ─────────────────────────────────────────────
# Citation extractor
# ─────────────────────────────────────────────

def extract_citations(
    answer: str,
    chunks: list[RetrievedChunk]
) -> tuple[str, list[Citation]]:
    """
    Parse the JSON block at the end of the answer to find which
    papers were cited, then return clean answer + Citation objects.
    """
    citations = []
    clean_answer = answer

    # Extract the JSON block
    try:
        json_start = answer.rfind("```json")
        json_end   = answer.rfind("```", json_start + 1)
        if json_start != -1 and json_end != -1:
            json_str     = answer[json_start + 7 : json_end].strip()
            parsed       = json.loads(json_str)
            cited_titles = parsed.get("citations_used", [])
            clean_answer = answer[:json_start].strip()

            # Match cited titles back to chunks
            seen_titles = set()
            for title in cited_titles:
                for chunk in chunks:
                    if (chunk.title.lower()[:40] in title.lower() or
                            title.lower() in chunk.title.lower()[:40]):
                        if chunk.title not in seen_titles:
                            seen_titles.add(chunk.title)
                            citations.append(Citation(
                                title   = chunk.title,
                                authors = chunk.authors,
                                year    = chunk.year,
                                doi     = chunk.doi,
                                section = chunk.section,
                                page    = chunk.page,
                            ))
                        break
    except (json.JSONDecodeError, ValueError):
        # If JSON parsing fails, fall back to including all retrieved chunks as citations
        log.warning("Could not parse citation JSON — listing all retrieved sources")
        seen = set()
        for chunk in chunks:
            if chunk.title not in seen:
                seen.add(chunk.title)
                citations.append(Citation(
                    title   = chunk.title,
                    authors = chunk.authors,
                    year    = chunk.year,
                    doi     = chunk.doi,
                    section = chunk.section,
                    page    = chunk.page,
                ))

    return clean_answer, citations





# ─────────────────────────────────────────────
# Fallback handler
# ─────────────────────────────────────────────

def handle_fallback(
    query: str,
    chunks: list,
    openai_client: OpenAI,
    reason: str,
) -> FallbackResult:
    """
    Called when retrieval fails or returns low-confidence results.
    Generates helpful suggestions and surfaces related topics actually
    present in the retrieved (but weak) chunks.

    reason: "no_results" | "low_confidence"
    """
    log.info(f"  Fallback triggered: {reason}")

    # Extract clean topics from retrieved chunks
    # Filter out noise: URLs, dates, metadata artifacts, very short/long strings
    import re as _re
    related_topics = []
    if chunks:
        seen = set()
        for c in chunks[:6]:
            title   = (c.title   if hasattr(c, "title")   else c.get("title",   "")).strip()
            section = (c.section if hasattr(c, "section") else c.get("section", "")).strip()

            # Skip noisy titles/sections
            def is_noise(s):
                if not s or len(s) < 4 or len(s) > 120:
                    return True
                if _re.search(r'https?://', s):           return True  # URLs
                if _re.search(r'\d{4}[-/]\d{2}', s):    return True  # dates
                if _re.search(r'^TYPE\s', s, _re.I):     return True  # TYPE labels
                if _re.search(r'^Received:', s, _re.I):   return True  # submission metadata
                if _re.search(r'^(doi|isbn|issn):', s, _re.I): return True
                if s.lower() in ("library", "abstract", "references",
                                  "acknowledgements", "appendix"):
                    return True
                # Skip strings that are mostly non-alpha (junk OCR)
                alpha = sum(ch.isalpha() for ch in s)
                if alpha / max(len(s), 1) < 0.5:
                    return True
                return False

            if is_noise(title) or is_noise(section):
                continue

            key = f"{title} — {section}"
            if key not in seen:
                seen.add(key)
                related_topics.append(key)

    # Ask LLM to suggest rephrasing — grounded in what's actually in the papers
    suggestions = []
    topics_context = ""
    if related_topics:
        topics_context = (
            "\n\nThe paper collection contains content on these topics:\n"
            + "\n".join(f"- {t}" for t in related_topics)
            + "\n\nSteer your suggestions toward these topics where possible."
        )
    try:
        response = openai_client.chat.completions.create(
            model=FALLBACK_MODEL,
            max_tokens=200,
            temperature=0.5,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a research assistant. The user asked a question that didn't match "
                        "the paper collection well. Suggest 3 ways to rephrase their question using "
                        "terminology and topics actually present in the collection. "
                        "Each suggestion should be a complete question the user could directly ask. "
                        "Return exactly 3 suggestions, one per line, no numbering or bullets."
                        + topics_context
                    )
                },
                {"role": "user", "content": f"User asked: {query}"}
            ]
        )
        raw = response.choices[0].message.content.strip()
        suggestions = [s.strip() for s in raw.split("\n") if s.strip()][:3]
    except Exception as e:
        log.warning(f"  Fallback suggestions failed: {e}")
        # Fall back to topic-based suggestions if LLM call fails
        if related_topics:
            suggestions = [f"Tell me about {t.split(' — ')[0]}" for t in related_topics[:3]]
        else:
            suggestions = [
                f"What does the research say about {query}?",
                f"What methods are used to study {query}?",
                f"What are the main findings related to {query}?",
            ]

    if reason == "no_results":
        message = (
            "Nothing relevant found in your paper collection for this query. "
            "The topic may not be covered in the current papers, or try rephrasing "
            "with more specific terminology from the domain."
        )
    else:  # low_confidence
        message = (
            "Found some loosely related content but the relevance score was too low "
            "to answer reliably. Try rephrasing with more specific terms, "
            "or the topic may not be well-covered in these papers."
        )

    return FallbackResult(
        triggered      = True,
        reason         = reason,
        message        = message,
        suggestions    = suggestions,
        related_topics = related_topics,
    )


# ─────────────────────────────────────────────
# Query router
# ─────────────────────────────────────────────

def classify_query(query: str, openai_client: OpenAI) -> RouteResult:
    """
    Classify the query type and return a RouteResult with tuned
    retrieval parameters for that type.

    Falls back to "exploratory" defaults if classification fails.
    """
    if not ROUTING_ENABLED or openai_client is None:
        cfg = ROUTE_CONFIGS["exploratory"]
        return RouteResult(
            query_type="exploratory",
            top_k=cfg["top_k"],
            mmr_lambda=cfg["mmr_lambda"],
            prompt_hint=cfg["prompt_hint"],
            section_filter=cfg["section_filter"],
        )

    try:
        response = openai_client.chat.completions.create(
            model=ROUTING_MODEL,
            max_tokens=10,
            temperature=0.0,
            messages=[
                {"role": "system", "content": ROUTING_PROMPT},
                {"role": "user",   "content": query},
            ],
        )
        raw  = response.choices[0].message.content.strip().lower()
        qtype = raw if raw in ROUTE_CONFIGS else "exploratory"
        log.info(f"  Query type: {qtype}")

    except Exception as e:
        log.warning(f"  Query routing failed ({e}) — defaulting to exploratory")
        qtype = "exploratory"

    cfg = ROUTE_CONFIGS[qtype]
    return RouteResult(
        query_type     = qtype,
        top_k          = cfg["top_k"],
        mmr_lambda     = cfg["mmr_lambda"],
        prompt_hint    = cfg["prompt_hint"],
        section_filter = cfg["section_filter"],
    )


# ─────────────────────────────────────────────
# Faithfulness checker
# ─────────────────────────────────────────────

def check_faithfulness(
    answer: str,
    chunks: list[RetrievedChunk],
    openai_client: OpenAI,
) -> FaithfulnessResult:
    """
    Run a second LLM call to verify every claim in the answer
    is supported by the retrieved source chunks.

    Returns a FaithfulnessResult with a score (0-100), verdict,
    lists of supported/unsupported claims, and a summary sentence.
    """
    if not FAITHFULNESS_ENABLED:
        return None

    context = build_context(chunks)

    try:
        response = openai_client.chat.completions.create(
            model=FAITHFULNESS_MODEL,
            temperature=0.0,    # deterministic — this is a checking task
            max_tokens=600,
            messages=[
                {"role": "system", "content": FAITHFULNESS_PROMPT},
                {"role": "user",   "content": (
                    f"ANSWER TO CHECK:\n{answer}\n\n"
                    f"SOURCE CHUNKS:\n{context}"
                )},
            ],
        )
        raw = response.choices[0].message.content.strip()

        # Strip markdown fences if present
        if raw.startswith("```"):
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
        raw = raw.strip()

        parsed = json.loads(raw)
        result = FaithfulnessResult(
            score              = int(parsed.get("score", 50)),
            verdict            = parsed.get("verdict", "PARTIALLY_FAITHFUL"),
            supported_claims   = parsed.get("supported_claims", []),
            unsupported_claims = parsed.get("unsupported_claims", []),
            summary            = parsed.get("summary", ""),
        )
        log.info(f"  Faithfulness: {result.badge()} — {result.summary}")
        return result

    except Exception as e:
        log.warning(f"  Faithfulness check failed ({e}) — skipping")
        return FaithfulnessResult(
            score=50, verdict="PARTIALLY_FAITHFUL",
            supported_claims=[], unsupported_claims=[],
            summary="Faithfulness check could not be completed."
        )


# ─────────────────────────────────────────────
# Main generation function
# ─────────────────────────────────────────────

def generate(
    query: str,
    qdrant_client: QdrantClient,
    openai_client: OpenAI,
    top_k: int = TOP_K_CHUNKS,
    filters: dict = None,
    mode: str = "balanced",
) -> RAGResponse:
    """
    Full RAG pipeline:
      query → retrieve chunks → build prompt → GPT-4o-mini → parse citations
    """

    # Step 1: Route — classify query type and get tuned retrieval params
    log.info(f"Routing query: '{query}'")
    route = classify_query(query, openai_client)

    # Use route's top_k unless caller explicitly passed one
    effective_top_k = top_k if top_k != TOP_K_CHUNKS else route.top_k
    route_config = {
        "top_k":          effective_top_k,
        "mmr_lambda":     route.mmr_lambda,
        "section_filter": route.section_filter,
    }

    # Step 2: Retrieve with route-tuned config
    log.info(f"Retrieving chunks for: '{query}'")
    chunks = retrieve(query, qdrant_client, top_k=effective_top_k,
                      filters=filters, openai_client=openai_client,
                      route_config=route_config, mode=mode)

    # Step 3: Fallback check — no results
    if not chunks:
        fallback = handle_fallback(query, [], openai_client, reason="no_results")
        return RAGResponse(
            query      = query,
            answer     = fallback.message,
            citations  = [],
            query_type = route.query_type,
            fallback   = fallback,
        )

    # Step 3b: Fallback check — low confidence (all reranker scores below threshold)
    top_score = max((c.score for c in chunks), default=0.0)
    if top_score < FALLBACK_SCORE_THRESHOLD:
        log.info(f"  Low confidence: top score={top_score:.3f} < threshold={FALLBACK_SCORE_THRESHOLD}")
        fallback = handle_fallback(query, chunks, openai_client, reason="low_confidence")
        return RAGResponse(
            query      = query,
            answer     = fallback.message,
            citations  = [],
            query_type = route.query_type,
            fallback   = fallback,
        )

    # Step 4: Build context
    context = build_context(chunks)

    # Step 5: Call GPT-4o-mini with route-specific prompt hint
    log.info(f"Calling {OPENAI_MODEL} [{route.query_type}]...")
    user_message = f"""Based on the following research paper excerpts, answer this question.

QUESTION: {query}

INSTRUCTION: {route.prompt_hint}

SOURCES:
{context}

Remember to cite sources inline using [Author et al., Year] format, and end with the JSON citation block.
"""

    response = openai_client.chat.completions.create(
        model=OPENAI_MODEL,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": user_message},
        ],
    )

    raw_answer = response.choices[0].message.content.strip()
    log.info(f"Tokens used — prompt: {response.usage.prompt_tokens}, "
             f"completion: {response.usage.completion_tokens}")

    # Step 6: Parse citations
    clean_answer, citations = extract_citations(raw_answer, chunks)

    # Step 7: Faithfulness check
    log.info("Running faithfulness check...")
    faithfulness = check_faithfulness(clean_answer, chunks, openai_client)

    return RAGResponse(
        query        = query,
        answer       = clean_answer,
        citations    = citations,
        faithfulness = faithfulness,
        query_type   = route.query_type,
        fallback     = None,
    )


# ─────────────────────────────────────────────
# History-aware generation (used by the web UI)
# ─────────────────────────────────────────────

def generate_with_history(
    query: str,
    history: list[dict],
    qdrant_client: QdrantClient,
    openai_client: OpenAI,
    top_k: int = TOP_K_CHUNKS,
    filters: dict = None,
    mode: str = "balanced",
) -> RAGResponse:
    """
    Like generate(), but passes the full conversation history to OpenAI
    so the model can refer back to previous questions and answers.

    history = [{"role": "user"|"assistant", "content": "..."},  ...]
    """

    # Step 1: Route query
    log.info(f"Routing query: '{query}'")
    route = classify_query(query, openai_client)
    effective_top_k = top_k if top_k != TOP_K_CHUNKS else route.top_k
    route_config = {
        "top_k":          effective_top_k,
        "mmr_lambda":     route.mmr_lambda,
        "section_filter": route.section_filter,
    }

    # Step 2: Enrich short/vague queries with conversation context for retrieval
    # e.g. "what is that content you found" → "what are solar bears what is that content you found"
    retrieval_query = query
    if len(query.split()) < 8 and history:
        last_user = next(
            (m["content"] for m in reversed(history) if m["role"] == "user"), ""
        )
        last_asst_clean = ""
        for m in reversed(history):
            if m["role"] == "assistant":
                # Strip citation JSON block before using as context
                txt = m["content"]
                json_idx = txt.rfind("```json")
                if json_idx != -1:
                    txt = txt[:json_idx].strip()
                last_asst_clean = txt[:300]
                break
        if last_user:
            retrieval_query = f"{last_user} {query}".strip()
            log.info(f"  Retrieval query enriched: '{retrieval_query[:80]}...'")

    # Step 3: Retrieve with enriched query + route config
    log.info(f"Retrieving chunks for: '{retrieval_query}'")
    chunks = retrieve(retrieval_query, qdrant_client, top_k=effective_top_k,
                      filters=filters, openai_client=openai_client,
                      route_config=route_config, mode=mode)

    if not chunks:
        fallback = handle_fallback(query, [], openai_client, reason="no_results")
        return RAGResponse(
            query=query, answer=fallback.message, citations=[],
            query_type=route.query_type, fallback=fallback,
        )

    # Step 4: Low confidence fallback
    top_score = max((c.score for c in chunks), default=0.0)
    if top_score < FALLBACK_SCORE_THRESHOLD:
        fallback = handle_fallback(query, chunks, openai_client, reason="low_confidence")
        return RAGResponse(
            query=query, answer=fallback.message, citations=[],
            query_type=route.query_type, fallback=fallback,
        )

    # Step 5: Build context from retrieved chunks
    context = build_context(chunks)

    # Step 6: Clean history for LLM context
    # Strip citation JSON blocks and long source text from assistant messages
    # so the conversation history stays concise and readable
    def clean_for_history(msg: dict) -> dict:
        if msg["role"] != "assistant":
            return msg
        txt = msg["content"]
        # Remove trailing ```json ... ``` block
        json_idx = txt.rfind("```json")
        if json_idx != -1:
            txt = txt[:json_idx].strip()
        # Remove SOURCES: blocks if they leaked into history
        src_idx = txt.find("\nSOURCES:\n")
        if src_idx != -1:
            txt = txt[:src_idx].strip()
        return {"role": "assistant", "content": txt}

    prior = history[-20:] if len(history) > 20 else history
    prior_clean = [clean_for_history(m) for m in prior]

    # Step 7: Assemble messages — system + clean history + new user turn with sources
    user_message = f"""Based on the following research paper excerpts, answer this question.
If the question refers to something discussed earlier in our conversation, use that context too.

QUESTION: {query}

INSTRUCTION: {route.prompt_hint}

SOURCES:
{context}

Remember to cite sources inline using [Author et al., Year] format, and end with the JSON citation block.
"""

    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages.extend(prior_clean)
    messages.append({"role": "user", "content": user_message})

    # Step 8: Call OpenAI
    log.info(f"Calling {OPENAI_MODEL} with {len(prior_clean)} prior messages...")
    response = openai_client.chat.completions.create(
        model=OPENAI_MODEL,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        messages=messages,
    )

    raw_answer = response.choices[0].message.content.strip()
    log.info(f"Tokens used — prompt: {response.usage.prompt_tokens}, "
             f"completion: {response.usage.completion_tokens}")

    # Step 9: Parse citations
    clean_answer, citations = extract_citations(raw_answer, chunks)

    # Step 10: Faithfulness check (deep mode only)
    faithfulness = None
    if mode == "deep":
        log.info("Running faithfulness check (deep mode)...")
        faithfulness = check_faithfulness(clean_answer, chunks, openai_client)

    return RAGResponse(
        query        = query,
        answer       = clean_answer,
        citations    = citations,
        faithfulness = faithfulness,
        query_type   = route.query_type,
        fallback     = None,
    )


