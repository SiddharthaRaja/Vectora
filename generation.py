# ─────────────────────────────────────────────
# Data model
# ─────────────────────────────────────────────

@dataclass
class Citation:
    title:   str
    authors: str
    year:    str
    doi:     str
    section: str
    page:    int

    def format(self) -> str:
        author_short = self.authors.split(",")[0].strip() if self.authors else "Unknown"
        year = self.year or "n.d."
        doi_str = f" DOI: {self.doi}" if self.doi else ""
        return f"{author_short} et al. ({year}) — {self.title[:60]} [{self.section}, p.{self.page}]{doi_str}"


@dataclass
class RouteResult:
    query_type:  str          # factual | comparative | methodological | definitional | exploratory | causal
    top_k:       int
    mmr_lambda:  float
    prompt_hint: str
    section_filter: str | None


@dataclass
class FallbackResult:
    triggered:        bool
    reason:           str        # "no_results" | "low_confidence" | "none"
    message:          str        # human-readable explanation shown to user
    suggestions:      list[str]  # rephrasing suggestions
    related_topics:   list[str]  # topics actually found in the DB


@dataclass
class FaithfulnessResult:
    score:              int           # 0-100
    verdict:            str           # FAITHFUL | MOSTLY_FAITHFUL | PARTIALLY_FAITHFUL | UNFAITHFUL
    supported_claims:   list[str]
    unsupported_claims: list[str]
    summary:            str

    def badge(self) -> str:
        icons = {
            "FAITHFUL":           "✓",
            "MOSTLY_FAITHFUL":    "~",
            "PARTIALLY_FAITHFUL": "!",
            "UNFAITHFUL":         "✗",
        }
        return f"{icons.get(self.verdict, '?')} {self.score}% faithful"


@dataclass
class RAGResponse:
    query:         str
    answer:        str
    citations:     list[Citation]
    faithfulness:  "FaithfulnessResult | None" = None
    query_type:    str = "unknown"
    fallback:      "FallbackResult | None" = None

    def pretty_print(self):
        print(f"\n{'='*60}")
        print(f"Query: {self.query}")
        print(f"{'='*60}")
        print(f"\n{self.answer}")
        if self.faithfulness:
            print(f"\n  [{self.faithfulness.badge()}] {self.faithfulness.summary}")
            if self.faithfulness.unsupported_claims:
                print("  Unsupported claims:")
                for c in self.faithfulness.unsupported_claims:
                    print(f"    ✗ {c}")
        if self.citations:
            print(f"\n{'─'*60}")
            print("References:")
            for i, c in enumerate(self.citations, 1):
                print(f"  [{i}] {c.format()}")
        print()


